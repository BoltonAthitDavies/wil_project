#!/usr/bin/env python3
"""Real-rig latency and resources, one row per run, in the columns of table 4.10.

    python3 script/exp1_real_resources.py

Applies analyse_exp3_rules.resources_for (= analyse_relogged_runs.summarize_run and
module_values, exactly as the simulation tables use them) to the fifteen reported
real-rig runs: the twelve patch-15 ORB-SLAM3 runs and the three VINS-Fusion
rate1_002 runs on realv7_000-002. Nothing new is measured; the nodes logged the same
performance.csv / module CSVs on the rig as in simulation.

Columns: front-end and back-end median module latency, throughput (processed frames
per second of sensor time), kept (processed / received by the node), and separately
received / bag (the share of the bag's 30 Hz frames that reached the node at all,
which in simulation is ~100 % and on the rig is not), CPU % of one core, peak RSS.

Writes output/compare/real/exp1-resources/real_resources.{csv,tex}; chat-first, not
included in the report.
"""
import csv
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "script"))
import analyse_exp3_rules as X                                        # noqa: E402

OUT = ROOT / "output/compare/real/exp1-resources"
DSS = ["dataset_realv6_000", "dataset_realv7_000", "dataset_realv7_001", "dataset_realv7_002"]
import re
REP = re.compile(r"^(?P<base>.+?)(?:_(?P<rep>\d{2}))?$")
ORB = [("GPU, LC on", "loopclosing_rate1", "lc_gpu"), ("GPU, LC off", "noloopclosing_rate1", "nolc_gpu"),
       ("CPU, LC on", "loopclosing_rate1_cpu", "lc_cpu"), ("CPU, LC off", "noloopclosing_rate1_cpu", "nolc_cpu")]
VINS_RUN = "rate1_002"


def metrics(sub):
    p = ROOT / "output/compare/real" / sub / "real_gt_metrics.csv"
    return list(csv.DictReader(open(p)))[0] if p.exists() else {}


def repeats(base_dir, run):
    """the reported run directory and its repeats run_01, run_02, ... (same configuration, re-played)"""
    out = [(run, 0)] if (base_dir / run).exists() else []
    for d in sorted(base_dir.glob(run + "_[0-9][0-9]")):
        out.append((d.name, int(d.name[-2:])))
    return out


TABLES = ROOT / "docs/report/final_report/tables"


def bag_frames(ds):
    """the bag's frame count at 30 Hz, from the scorer manifest of a run scored with the bag present"""
    import json
    for sub in (f"{ds[8:]}_lc_gpu_p15", f"{ds[8:]}_lc_gpu_p15_r01", f"{ds[8:]}_vins_{VINS_RUN}"):
        mf = ROOT / "output/compare/real" / sub / ds / "manifest.json"
        if mf.exists():
            b = json.load(open(mf))["bag"]
            if b.get("substituted_from") is None and b.get("duration_s"):
                return int(round(b["duration_s"] * 30))
    return None


def write_tex(rows):
    import numpy as np
    f1 = lambda v, p=1: ("%.*f" % (p, v)) if np.isfinite(v) else "---"
    pm = lambda vals, p=1: "%.*f $\\pm$ %.*f" % (p, np.mean(vals), p, np.std(vals, ddof=1))
    # ---- one row per run, the realv7 recordings (the form of the realistic-world table)
    L = [r"% Generated by script/exp1_real_resources.py -- do not edit by hand.", r"\begin{table}[htbp]", r"\centering",
         r"\caption[Real-time and resource measurements of the fifteen reported real-robot runs.]{Real robot, real-time and "
         r"resource measurements, one row per run, in the columns of \cref{tab:realistic-resources}: the twelve ORB-SLAM3 runs with "
         r"fork patch 15 and the three VINS-Fusion runs of \cref{tab:realv7-vins}, every one the deployment condition --- bag "
         r"replayed at rate 1.0, node live on the laptop. Front-end and back-end are each run's median module "
         r"latency (ORB-SLAM3: tracking and local mapping; VINS-Fusion: feature tracking and back-end optimization); throughput "
         r"is processed frames per second of sensor time; ``kept'' is processed over received by the node, and ``received'' is "
         r"what reached the node against the bag's frames at \SI{30}{\hertz}, a column the simulation tables do not need "
         r"because there it is \SIrange{97}{100}{\percent}. CPU is the process average in percent of one core and RSS the "
         r"peak resident set. \flag{The three VINS-Fusion rows were recorded on a thermally throttled laptop "
         r"(\cref{tab:real-resources-repeats}); their latency is about twice, and their received share about half, what the "
         r"same configuration gives when the machine is cool.}}",
         r"\label{tab:real-resources-runs}", r"\scriptsize", r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{llrrrrrrr}", r"\toprule",
         r"Recording & Run & Front-end [\si{\milli\second}] & Back-end [\si{\milli\second}] & Throughput [\si{\hertz}] & Kept [\si{\percent}] & Received [\si{\percent}] & CPU [\si{\percent}] & Peak RSS [\si{\mebi\byte}] \\",
         r"\midrule"]
    last = None
    for r in rows:
        if r["dataset"].startswith("realv6") or r["rep"] != 0:
            continue
        nb = bag_frames("dataset_" + r["dataset"]); rec = 100.0 * r["received"] / nb if nb else float("nan")
        name = ("ORB-SLAM3 " + r["run"]) if r["system"] == "ORB-SLAM3" else "VINS-Fusion"
        lead = (r"\repo{%s}" % r["dataset"]) if r["dataset"] != last else ""
        if r["dataset"] != last and last is not None:
            L.append(r"\addlinespace")
        last = r["dataset"]
        L.append(f"{lead} & {name} & {f1(r['front_ms'])} & {f1(r['back_ms'])} & {f1(r['throughput_hz'])} & "
                 f"{f1(r['kept_pct'], 0)} & {f1(rec, 0)} & {f1(r['cpu_pct'], 0)} & {f1(r['rss_peak_mb'], 0)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    (TABLES / "real_resources_runs.tex").write_text("\n".join(L) + "\n")
    # ---- mean +- SD over repeats, the realv6 recording (the form of the mapping-recording table)
    L = [r"% Generated by script/exp1_real_resources.py -- do not edit by hand.", r"\begin{table}[htbp]", r"\centering",
         r"\caption[Real-time and resource measurements repeated on the real robot.]{Real-time and resource measurements on "
         r"\repo{dataset_realv6_000}, replay rate 1.0: mean $\pm$ SD over $n$ repeats of each configuration, "
         r"in the columns of \cref{tab:mapping-resources}. The recording's tracker export fails the validity rules, so its "
         r"accuracy is a diagnostic only; latency and resources need no truth. Columns as in "
         r"\cref{tab:real-resources-runs}. The ORB-SLAM3 repeats agree to within \SI{4}{\percent} on back-end latency, "
         r"CPU and memory; the CPU front end's wider spread is the laptop's temperature. \flag{One of the three VINS-Fusion "
         r"runs was recorded while the laptop was thermally throttled (front end \SI{108}{\milli\second}, \SI{7.4}{\hertz}) "
         r"and the other two cool (\SIrange{55}{57}{\milli\second}, \SI{13.5}{\hertz}); the VINS-Fusion row is therefore "
         r"a mixture of two machine states and its SD measures the throttling, not the estimator.}}",
         r"\label{tab:real-resources-repeats}", r"\small", r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lllc rrrrrr}", r"\toprule",
         r"Recording & Estimator & Run & $n$ & Front-end [\si{\milli\second}] & Back-end [\si{\milli\second}] & Throughput [\si{\hertz}] & Kept [\si{\percent}] & CPU [\si{\percent}] & Peak RSS [\si{\mebi\byte}] \\",
         r"\midrule"]
    seen = []
    for r in rows:
        k = (r["dataset"], r["system"], r["run"])
        if not r["dataset"].startswith("realv6") or k in seen:
            continue
        seen.append(k); g = [x for x in rows if (x["dataset"], x["system"], x["run"]) == k]
        if len(g) < 2:
            continue
        lead = (r"\repo{%s}" % r["dataset"]) if len(seen) == 1 else ""
        L.append(f"{lead} & {r['system']} & {r['run'] if r['system'] == 'ORB-SLAM3' else 'fov 70, extrinsic fixed'} & {len(g)} & "
                 f"{pm([x['front_ms'] for x in g])} & {pm([x['back_ms'] for x in g])} & {pm([x['throughput_hz'] for x in g])} & "
                 f"{pm([x['kept_pct'] for x in g], 0)} & {pm([x['cpu_pct'] for x in g], 0)} & {pm([x['rss_peak_mb'] for x in g], 0)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    (TABLES / "real_resources_repeats.tex").write_text("\n".join(L) + "\n")
    print("wrote", TABLES / "real_resources_runs.tex", "and real_resources_repeats.tex")


def main():
    rows = []
    for ds in DSS:
        for lbl, run, key in ORB:
            for name, rep in repeats(ROOT / "output/output_orb/real" / ds, run):
                d = ROOT / "output/output_orb/real" / ds / name
                res = X.resources_for(dict(path=d, tree="output_orb", system="ORB-SLAM3", dataset=ds, repeat=name))
                m = metrics(f"{ds[8:]}_{key}_p15") if rep == 0 else {}
                rows.append(dict(dataset=ds[8:], system="ORB-SLAM3", run=lbl, rep=rep, ate=float(m.get("ate_rmse", "nan")), **res))
        for name, rep in repeats(ROOT / "output/output_vins/real" / ds, VINS_RUN):
            d = ROOT / "output/output_vins/real" / ds / name
            res = X.resources_for(dict(path=d, tree="output_vins", system="VINS-Fusion", dataset=ds, repeat=name))
            m = metrics(f"{ds[8:]}_vins_{VINS_RUN}") if rep == 0 else {}
            rows.append(dict(dataset=ds[8:], system="VINS-Fusion", run="fov 70, extr. fixed", rep=rep, ate=float(m.get("ate_rmse", "nan")), **res))
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "real_resources.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    print("%-11s %-11s %-20s %3s %6s %8s %8s %7s %6s %6s %8s %6s" % ("recording", "estimator", "run", "rep", "ATE", "front ms", "back ms", "thr Hz", "kept%", "CPU%", "RSS MiB", "recvd"))
    for r in rows:
        print("%-11s %-11s %-20s %3d %6.3f %8.1f %8.1f %7.1f %6.0f %6.0f %8.0f %6d" % (
            r["dataset"], r["system"], r["run"], r["rep"], r["ate"], r["front_ms"], r["back_ms"], r["throughput_hz"], r["kept_pct"], r["cpu_pct"], r["rss_peak_mb"], r["received"]))
    write_tex(rows)
    import numpy as np
    print("\nmean +- SD over repeats where n > 1 (table 4.9 form):")
    seen = []
    for r in rows:
        k = (r["dataset"], r["system"], r["run"])
        if k in seen:
            continue
        seen.append(k); g = [x for x in rows if (x["dataset"], x["system"], x["run"]) == k]
        if len(g) < 2:
            continue
        pm = lambda c, p=1: "%.*f +- %.*f" % (p, np.mean([x[c] for x in g]), p, np.std([x[c] for x in g], ddof=1))
        print("  %-11s %-11s %-20s n=%d  front %s  back %s  thr %s  kept %s  CPU %s  RSS %s" % (
            k[0], k[1], k[2], len(g), pm("front_ms"), pm("back_ms"), pm("throughput_hz"), pm("kept_pct", 0), pm("cpu_pct", 0), pm("rss_peak_mb", 0)))
    print("\nwrote", OUT / "real_resources.csv")


if __name__ == "__main__":
    main()
