#!/usr/bin/env python3
"""Why does no visual run reach the 0.05 m ATE target? Split 3-D ATE into floor plane and height.

Diagnostic for Experiment 1 (simulation, realistic_000-003, the reported
ORB-SLAM3 arms and VINS-Fusion `cpu`). For each run:
  ate3d    the usual rigid SE(3) fit, RMS of 3-D error (IMU-point GT)
  z_rms    RMS of the vertical component of that same residual
  ate2d    SE(2) fit of x-y only, RMS of planar error
  med2d / p95_2d / under5cm   distribution of the planar error
  best_dt  time offset (+-0.4 s) that minimizes ate3d -- rules timing in or out

  ate_full whole-run 3-D ATE, no cut -- must reproduce tab:realistic-baseline

Everything except ate_full is computed AFTER the initialization transient, cut
exactly where analyse_realistic_runs.post_init_max cuts it (after the last jump
inside the first 15 s, plus 0.5 s), with the rigid fit redone on that segment.

POST-HOC: the 2-D view was added after the 3-D results were known. It explains
the miss; it does not change the target or the verdict.

Writes output/compare/simulation/exp1-planar-ate/planar_ate.csv and the report
table docs/report/final_report/tables/exp1_planar_ate.tex.
"""
import csv
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vio_metrics as vm  # noqa: E402

ROOT = vm.ROOT
OUT = os.path.join(ROOT, 'output', 'compare', 'simulation', 'exp1-planar-ate')
ORB_ARMS = ('loopclosing_gpu', 'loopclosing_cpu', 'noloopclosing_gpu', 'noloopclosing_cpu')
INIT_SEARCH_S, INIT_PAD_S = 15.0, 0.5   # = analyse_realistic_runs
TABLE = os.path.join(ROOT, 'docs', 'report', 'final_report', 'tables', 'exp1_planar_ate.tex')
OFFS = np.round(np.arange(-0.40, 0.401, 0.02), 2)


def se2(src, dst):
    cs, cd = src.mean(0), dst.mean(0)
    U, _, Vt = np.linalg.svd((src - cs).T @ (dst - cd))
    R = Vt.T @ U.T
    if np.linalg.det(R) < 0:
        Vt[-1] *= -1
        R = Vt.T @ U.T
    return R, cd - R @ cs


def init_cut(t, p):
    """Start of the post-initialization segment, as post_init_max defines it."""
    jumps = vm.find_jumps(t, p)[0]
    early = [j for j in jumps if t[j + 1] <= t[0] + INIT_SEARCH_S]
    return (t[early[-1] + 1] + INIT_PAD_S) if early else t[0]


def score(t, p, gt_t, gp, off=0.0, t_from=None):
    tt = t + off
    m = (tt > gt_t[0] + 0.5) & (tt < gt_t[-1] - 0.5)
    if t_from is not None:
        m &= t >= t_from
    ref = np.column_stack([np.interp(tt[m], gt_t, gp[:, k]) for k in range(3)])
    R, tr = vm.umeyama(p[m], ref)
    d3 = (R @ p[m].T).T + tr - ref
    R2, t2 = se2(p[m][:, :2], ref[:, :2])
    e2 = np.linalg.norm((R2 @ p[m][:, :2].T).T + t2 - ref[:, :2], axis=1)
    return dict(ate3d=float(np.sqrt((np.linalg.norm(d3, axis=1) ** 2).mean())),
                z_rms=float(np.sqrt((d3[:, 2] ** 2).mean())),
                ate2d=float(np.sqrt((e2 ** 2).mean())), med2d=float(np.median(e2)),
                p95_2d=float(np.percentile(e2, 95)), under5cm=float((e2 < 0.05).mean()))


LABEL = {'ORB loopclosing_cpu': 'ORB-SLAM3', 'ORB loopclosing_gpu': 'ORB-SLAM3 GPU',
         'ORB noloopclosing_cpu': 'ORB-SLAM3 (no LC)', 'ORB noloopclosing_gpu': 'ORB-SLAM3 GPU (no LC)',
         'VINS': 'VINS-Fusion'}
ORDER = ['ORB loopclosing_cpu', 'ORB loopclosing_gpu', 'ORB noloopclosing_cpu', 'ORB noloopclosing_gpu', 'VINS']
LAYOUT = {'000': 'U', '001': 'I', '002': 'U', '003': 'I'}
DIVERGED_M = 1.0   # whole-run ATE above this = the five diverged runs of tab:realistic-baseline


def write_table(rows):
    ok = [r for r in rows if r['ate_full'] <= DIVERGED_M]
    dt_gain = max(r['ate3d'] - r['ate3d_best_dt'] for r in ok)
    lines = [
        '% Generated by script/exp1_planar_ate.py -- do not edit by hand.',
        r'\begin{table}[htbp]', r'\centering',
        (r"""\caption[Visual estimators split into floor-plane and height error (post-hoc).]{Visual estimators of """
         r"""\cref{tab:realistic-baseline} split into floor-plane and height error, a post-hoc diagnostic added after """
         r"""the results were known; it explains the miss of the \SI{0.05}{\metre} target and does not re-score it. """
         r"""``Whole run'' reproduces the ATE column of \cref{tab:realistic-baseline} (to within \SI{0.03}{\metre} on """
         r"""the five diverged runs and \SI{0.003}{\metre} on the rest; the resampling differs). Every other column """
         r"""starts after the initialization transient, cut where that table cuts its ``Max'' (after the last jump """
         r"""inside the first \SI{15}{\second}, plus \SI{0.5}{\second}), with the rigid fit redone on that segment: """
         r"""``3-D'' is its ATE, ``Height'' the RMS of the vertical component of the same residual, ``Planar'' the ATE """
         r"""after an $SE(2)$ fit of $x$--$y$ alone, ``Median'' the median planar error and """
         r"""``$<$\SI{5}{\centi\metre}'' the share of the run spent inside the target in the plane. \textbf{Bold}: """
         r"""planar ATE within the target. Shifting the estimate by up to $\pm$\SI{0.4}{\second} lowers the 3-D """
         r"""column of the runs that did not diverge by at most """
         + f'\\SI{{{dt_gain:.2f}}}{{\\metre}}' + r', so timing is not the cause.}'),
        r'\label{tab:exp1-planar-ate}', r'\small', r'\resizebox{\textwidth}{!}{%',
        r'\begin{tabular}{lll rrrrrr}', r'\toprule',
        r'Recording & Layout & Estimator & Whole run [\si{\metre}] & 3-D [\si{\metre}] & Height [\si{\metre}] & '
        r'Planar [\si{\metre}] & Median [\si{\metre}] & $<$\SI{5}{\centi\metre} [\si{\percent}] \\', r'\midrule']
    for k, ds in enumerate(('000', '001', '002', '003')):
        if k:
            lines.append(r'\addlinespace')
        for j, sysk in enumerate(ORDER):
            r = next((x for x in rows if x['dataset'] == ds and x['system'] == sysk), None)
            if r is None:
                continue
            pl = f"{r['ate2d']:.3f}"
            if r['ate2d'] <= 0.05:
                pl = r'\textbf{' + pl + '}'
            head = (r'\repo{realistic_' + ds + '} & ' + LAYOUT[ds]) if j == 0 else ' & '
            lines.append(f"{head} & {LABEL[sysk]} & {r['ate_full']:.3f} & {r['ate3d']:.3f} & {r['z_rms']:.3f} & "
                         f"{pl} & {r['med2d']:.3f} & {100 * r['under5cm']:.0f} \\\\")
    lines += [r'\bottomrule', r'\end{tabular}}', r'\end{table}', '']
    with open(TABLE, 'w') as f:
        f.write('\n'.join(lines))
    print(f'table: {TABLE}  (max timing gain on non-diverged runs {dt_gain:.3f} m)')


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for i in range(4):
        d = f'dataset_allsensor_realistic_00{i}'
        gt = vm.load(os.path.join(ROOT, 'dataset', 'gt', d, 'ground_truth.csv'))
        gp, gt_t = vm.gt_at_imu(gt[1], gt[2]), gt[0]
        runs = [(f'ORB {a}', os.path.join(ROOT, 'output', 'output_orb', 'simulation', d, a, 'vio.csv')) for a in ORB_ARMS]
        runs.append(('VINS', os.path.join(ROOT, 'output', 'output_vins', 'simulation', d, 'cpu', 'vio.csv')))
        for name, path in runs:
            r = vm.load(path)
            if r is None:
                print(f'{d} {name}: missing {path}')
                continue
            t, p = r[0], r[1]
            cut = init_cut(t, p)
            s = score(t, p, gt_t, gp, t_from=cut)
            s['ate_full'] = score(t, p, gt_t, gp)['ate3d']
            s['cut_s'] = float(cut - t[0])
            sweep = [score(t, p, gt_t, gp, o, t_from=cut)['ate3d'] for o in OFFS]
            k = int(np.argmin(sweep))
            s.update(dataset=d[-3:], system=name, best_dt=float(OFFS[k]), ate3d_best_dt=float(sweep[k]))
            rows.append(s)
    cols = ['dataset', 'system', 'cut_s', 'ate_full', 'ate3d', 'z_rms', 'ate2d', 'med2d', 'p95_2d', 'under5cm', 'best_dt', 'ate3d_best_dt']
    with open(os.path.join(OUT, 'planar_ate.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({c: (f'{r[c]:.4f}' if isinstance(r[c], float) else r[c]) for c in cols})
    print(f'{"ds":4}{"system":24}{"cut":>5}{"full":>7}{"ATE3D":>7}{"z_rms":>7}{"ATE2D":>7}{"med2D":>7}{"p95":>7}{"<5cm":>6}{"dt*":>7}{"ATE@dt*":>8}')
    for r in rows:
        print(f'{r["dataset"]:4}{r["system"]:24}{r["cut_s"]:5.1f}{r["ate_full"]:7.3f}{r["ate3d"]:7.3f}{r["z_rms"]:7.3f}{r["ate2d"]:7.3f}{r["med2d"]:7.3f}'
              f'{r["p95_2d"]:7.3f}{100*r["under5cm"]:5.0f}%{r["best_dt"]:+7.2f}{r["ate3d_best_dt"]:8.3f}')
    orb = [r for r in rows if r['system'].startswith('ORB')]
    hit = sorted(r['ate2d'] for r in orb if r['ate2d'] <= 0.05)
    print(f'\nORB-SLAM3 runs with planar ATE <= 0.05 m: {len(hit)} of {len(orb)} {hit}')
    write_table(rows)
    print(f'CSV: {os.path.join(OUT, "planar_ate.csv")}')


if __name__ == '__main__':
    main()
