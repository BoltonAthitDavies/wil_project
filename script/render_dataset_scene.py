#!/usr/bin/env python3
"""Render one dataset's scene: floor treatment, object layout, ground-truth route.

    python3 script/render_dataset_scene.py --dataset simulation/dataset_allsensor_004 \\
        --out docs/report/minor_report/figures/scene_allsensor_004.png

    python3 script/render_dataset_scene.py --all \\
        --out-dir docs/report/minor_report/figures

WHY ALL THREE IN ONE PICTURE
    A dataset in this project is not identified by its bag alone. Three things vary
    between recordings and all three change what an estimator sees:

      floor      plain (an untextured diffuse colour) or bayline (the same colour
                 plus fourteen painted bay outlines). Invisible to occupancy,
                 invisible to a wheel, and the only thing a downward-looking
                 feature detector has to work with on open floor.
      objects    which obstacles are present and where. The objonwallonly worlds
                 clear the central floor; the _01 and _02 arrangements populate it.
      route      where the robot actually drove. Two recordings in one world are
                 still different experiments if the routes differ, and route length
                 is what drift accumulates against.

    Reading those off three separate artifacts -- a world file, an occupancy grid
    and a CSV -- is what made it easy to treat dataset_allsensor_002 and _003 as
    repeats when they differ in floor, or to describe "textured versus featureless"
    as a bigger manipulation than it is. One picture per dataset makes the actual
    difference visible.

WHAT IS DRAWN, AND FROM WHERE
    floor       viewer.build_floor_array + viewer.paint_markings, via
                viewer.ground_assets(world) so the world's OWN ground model is
                resolved rather than a hardcoded one.
    objects     viewer.load_obstacles(world) -- convex hulls of each collision mesh
                sliced at robot height (viewer.Z_LO..Z_HI). Same geometry the
                occupancy bake and the live overlay use.
    route       ground_truth.csv, preferring the baseline trees and falling back to
                the relogged campaign's extracted copies.

    Dynamic props are drawn at their AUTHORED pose, which is where the world file
    puts them at t=0. They move during a dynamic recording and this picture does not
    show that; it is a layout figure, not a record of what was in front of the robot
    at any instant.
"""

import argparse
import os
import sys

os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import viewer
import vio_metrics as vm

ROOT = vm.ROOT
WORLDS = os.path.join(ROOT, 'aws-robomaker-small-warehouse-world', 'worlds')

OBJ_FILL = (60, 66, 78)
OBJ_EDGE = (34, 38, 46)
GT_COLOR = (0, 132, 255)
GT_START = (0, 176, 80)
GT_END = (214, 40, 40)


def world_for(dataset):
    """The .world recorded in a run manifest for this dataset, as an absolute path.

    Read from the manifest rather than guessed from the dataset name: the name says
    'nofloortexture' for datasets recorded in four different worlds, and
    dataset_static_nofloortexture_001 sits in the _01 arrangement while _000 and
    _002 sit in the canonical one.
    """
    for tree in ('output_orb', 'output_vins'):
        base = os.path.join(ROOT, 'output', tree, dataset)
        if not os.path.isdir(base):
            continue
        for run in sorted(os.listdir(base)):
            man = os.path.join(base, run, 'run_metadata.csv')
            if not os.path.exists(man):
                continue
            for line in open(man):
                if line.startswith('world_path,'):
                    return line.split(',', 1)[1].strip().strip('"')
    return None


# A world recorded in a manifest can be gone from disk. Two relogged-campaign
# datasets name small_warehouse_static_nofloortexture.world, which no longer
# exists. The floor variants are generated by make_plain_floor.py, which swaps ONLY
# the ground model's <include> uri and leaves every object untouched, so the object
# layout of a missing variant is exactly that of its base world. Substituting the
# base and forcing the recorded floor is therefore exact for geometry -- but it is
# a reconstruction, not the recorded file, and every caller is told so.
FLOOR_SUFFIX = {'_nofloortexture': 'aws_robomaker_warehouse_GroundB_01_plain',
                '_bayline': 'aws_robomaker_warehouse_GroundB_01_bayline'}


def substitute_world(world):
    """(base_world, forced_ground_model) for a missing floor variant, else None."""
    d, base = os.path.dirname(world), os.path.basename(world)
    stem = base[:-len('.world')] if base.endswith('.world') else base
    for suf, model in FLOOR_SUFFIX.items():
        if suf in stem:
            cand = os.path.join(d, stem.replace(suf, '') + '.world')
            if os.path.isfile(cand):
                return cand, model
    return None


def ground_assets_for_model(model):
    """viewer.ground_assets' tuple, for a ground model named directly."""
    base = viewer.bake_map.resolve_uri(model, viewer.MODELS)
    dae = os.path.join(base, 'meshes', os.path.basename(model) + '_visual.DAE')
    if not os.path.isfile(dae):
        return None
    diffuse = viewer._dae_diffuse(dae)
    n_marks = len(viewer._marking_faces(dae, viewer.MARK_MATERIAL))
    mark = diffuse.get(viewer.MARK_MATERIAL, {})
    concrete = next((v for k, v in diffuse.items() if k != viewer.MARK_MATERIAL),
                    {'image': None, 'color': None})
    return (dae, concrete['image'] or concrete['color'] or (0.5, 0.5, 0.5),
            mark.get('image') if n_marks else None, n_marks)


def gt_for(dataset):
    """Ground-truth CSV for a dataset, baseline trees first."""
    name = dataset.split('/')[-1]
    cands = [os.path.join(ROOT, 'output', t, dataset, 'ground_truth.csv')
             for t in ('output_wheel', 'output_imu', 'output_ekf')]
    cands.append(os.path.join(ROOT, 'output', 'compare', 'relogged_20260916',
                              'ground_truth', name + '.csv'))
    for c in cands:
        if os.path.exists(c):
            return c
    return None


def to_px(xy, ppm):
    """World metres -> image pixels, using the floor rect viewer rasterises."""
    c = (xy[:, 0] - viewer.FLOOR_X0) * ppm
    r = (viewer.FLOOR_Y1 - xy[:, 1]) * ppm
    return np.stack([c, r], axis=1)


def render(dataset, ppm, flip='', show_gt=True):
    world = world_for(dataset)
    if world is None:
        raise SystemExit('no world recorded for %s (looked in run manifests)' % dataset)

    recorded, substituted = world, None
    assets = None
    if os.path.isfile(world):
        assets = viewer.ground_assets(world)
    else:
        sub = substitute_world(world)
        if sub is None:
            raise SystemExit('recorded world is missing and not reconstructible: %s'
                             % world)
        world, model = sub
        assets = ground_assets_for_model(model)
        substituted = model
    if assets is None:
        raise SystemExit('no GroundB model in %s' % world)
    dae, concrete, atlas, n_marks = assets
    img = viewer.build_floor_array(concrete, ppm, flip)
    if atlas and n_marks:
        viewer.paint_markings(img, ppm, flip, dae_path=dae, atlas_path=atlas)

    pil = Image.fromarray(img).convert('RGB')
    dr = ImageDraw.Draw(pil)

    # load_obstacles returns (obstacles, wall); its docstring describes only the
    # first element, and unpacking the pair as a triple fails with a message about
    # the polygon list rather than about the pair.
    obstacles, wall = viewer.load_obstacles(world)
    for _label, poly, _pose in obstacles:
        pts = [tuple(p) for p in to_px(np.asarray(poly, dtype=float), ppm)]
        if len(pts) >= 3:
            dr.polygon(pts, fill=OBJ_FILL, outline=OBJ_EDGE)
    if wall is not None:
        # Drawn as a ring, not a filled hull: the wall's convex hull is the whole
        # floor, which would paint over everything already rendered.
        x0, y0, x1, y1 = wall
        c0, r0 = to_px(np.array([[x0, y1]]), ppm)[0]
        c1, r1 = to_px(np.array([[x1, y0]]), ppm)[0]
        dr.rectangle([c0, r0, c1, r1], outline=OBJ_EDGE,
                     width=max(2, int(round(0.20 * ppm))))

    gt_info = None
    if show_gt:
        g = gt_for(dataset)
        if g is not None:
            a = np.loadtxt(g, delimiter=',', ndmin=2)
            xy = a[:, 1:3]
            pts = [tuple(p) for p in to_px(xy, ppm)]
            dr.line(pts, fill=GT_COLOR, width=max(2, int(round(0.06 * ppm))))
            r = max(3, int(round(0.18 * ppm)))
            for p, col in ((pts[0], GT_START), (pts[-1], GT_END)):
                dr.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=col)
            length = float(np.linalg.norm(np.diff(xy, axis=0), axis=1).sum())
            t = a[:, 0] * 1e-9
            gt_info = dict(path=g, samples=len(xy), length_m=length,
                           span_s=float(t[-1] - t[0]))

    return pil, dict(world=recorded, world_drawn=world,
                     substituted=substituted, ground=os.path.basename(os.path.dirname(
        os.path.dirname(dae))), markings=n_marks,
        textured=bool(atlas and n_marks), obstacles=len(obstacles),
        wall=wall is not None, gt=gt_info)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dataset', help="'group/name', e.g. simulation/dataset_allsensor_004")
    ap.add_argument('--all', action='store_true',
                    help='every dataset under output/output_orb/simulation with a manifest')
    ap.add_argument('--out', help='output PNG for a single --dataset')
    ap.add_argument('--out-dir', help='directory for --all')
    ap.add_argument('--ppm', type=float, default=20.0)
    ap.add_argument('--flip', default='', choices=['', 'u', 'v', 'uv'])
    ap.add_argument('--no-gt', action='store_true')
    ap.add_argument('--table',
                    help='also write a LaTeX registry table of what was rendered')
    a = ap.parse_args()

    if a.all:
        base = os.path.join(ROOT, 'output', 'output_orb', 'simulation')
        names = ['simulation/' + n for n in sorted(os.listdir(base))
                 if os.path.isdir(os.path.join(base, n))]
        outdir = a.out_dir or os.path.join(ROOT, 'docs', 'report', 'minor_report',
                                           'figures')
        os.makedirs(outdir, exist_ok=True)
        targets = [(n, os.path.join(outdir, 'scene_%s.png'
                                    % n.split('/')[-1].replace('dataset_', '')))
                   for n in names]
    else:
        if not a.dataset or not a.out:
            raise SystemExit('need --dataset and --out, or --all')
        targets = [(a.dataset, a.out)]

    rows = []
    for ds, out in targets:
        try:
            pil, info = render(ds, a.ppm, a.flip, show_gt=not a.no_gt)
        except SystemExit as e:
            print('  [skip] %s: %s' % (ds, e))
            continue
        pil.save(out)
        g = info['gt']
        rows.append((ds.split('/')[-1], info))
        note = '  [world reconstructed: %s]' % info['substituted'] if info['substituted'] else ''
        print('  %-44s %-9s obj=%-4d %s -> %s%s'
              % (ds.split('/')[-1],
                 'bayline' if info['textured'] else 'plain',
                 info['obstacles'],
                 ('route %.1f m' % g['length_m']) if g else 'no ground truth',
                 os.path.relpath(out, ROOT), note))
    if a.table and rows:
        write_table(a.table, rows)
        print('  table -> %s' % os.path.relpath(a.table, ROOT))


def write_table(path, rows):
    """Registry of what each dataset actually contains, from the rendered scenes.

    Generated rather than typed so the caption's numbers cannot drift from the
    pictures beside them: both come from the same pass over the manifests, the
    world files and the ground-truth CSVs.
    """
    with open(path, 'w') as f:
        f.write('%% Generated by script/render_dataset_scene.py -- do not edit.\n')
        f.write('\\begin{tabularx}{\\textwidth}{>{\\raggedright\\arraybackslash}X'
                'llrrrr}\n\\toprule\n')
        f.write('Dataset & World & Floor & Objects & Route & Sim span & Truth'
                ' \\\\\n')
        f.write(' & arrangement & & & [\\si{\\metre}] & [\\si{\\second}]'
                ' & samples \\\\\n\\midrule\n')
        for name, info in rows:
            w = os.path.basename(info['world'])
            w = w[len('small_warehouse_'):] if w.startswith('small_warehouse_') else w
            w = w[:-len('.world')] if w.endswith('.world') else w
            for suf in ('_nofloortexture', '_bayline'):
                w = w.replace(suf, '')
            g = info['gt']
            flag = '\\flag{*}' if info['substituted'] else ''
            # \repo detokenises its argument, so a pre-escaped \_ arrives as a
            # literal backslash followed by an underscore. It takes raw underscores.
            f.write('\\repo{%s}%s & \\texttt{%s} & %s & %d & %s & %s & %s \\\\\n'
                    % (name, flag,
                       w.replace('_', '\\_') or 'canonical',
                       'bayline' if info['textured'] else 'plain',
                       info['obstacles'],
                       ('%.1f' % g['length_m']) if g else '--',
                       ('%.1f' % g['span_s']) if g else '--',
                       ('%d' % g['samples']) if g else '--'))
        f.write('\\bottomrule\n\\end{tabularx}\n')


if __name__ == '__main__':
    main()
