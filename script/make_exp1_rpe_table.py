#!/usr/bin/env python3
"""Emit the Experiment 1 relative-pose-error table from the scored metrics.

    python3 script/make_exp1_rpe_table.py            # write the table
    python3 script/make_exp1_rpe_table.py --check    # print, write nothing

WHY THIS EXISTS
  This table was hand-written inline in the Experiment 1 note, and the hand
  drifted: 27 of its 28 rows carried the delta = 0.5 s figures while the
  caption, the title, the List of Tables and the prose all said 1 s, and one
  row -- realistic_002, ORB-SLAM3 GPU with the closer active -- carried the
  1 s figures, so that recording compared a 1 s number against 0.5 s ones.
  Nothing detected it because nothing generated it.  Now something does.

SOURCE
  output/compare/simulation/exp1-realistic/proprio_rpe_metrics.csv, the file
  analyse_realistic_runs.py writes from vio_metrics.rpe() on the UNALIGNED
  poses.  Spot-checked against a direct recomputation from vio.csv: on
  realistic_002 VINS-Fusion at delta = 1 s it gives 0.06956 against the file's
  0.06958, five decimals.

  NOT output/compare/simulation/exp3-rules/realistic_resources.csv.  Its
  `rpe1_clean` column reconciles with neither delta and is 2-4x these values
  on all twenty runs; it is a different quantity and must not be quoted as
  relative pose error until someone identifies what it measures.
"""

import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "output/compare/simulation/exp1-realistic/proprio_rpe_metrics.csv")
OUT = os.path.join(ROOT, "docs/report/final_report/tables/exp1_rpe_table.tex")
DELTA = "1"                      # the interval the caption promises

BAGS = ["simulation/dataset_allsensor_realistic_%03d" % i for i in range(4)]
# source name -> printed label, in the order the table lists them
ARMS = [("Wheel odometry", "Wheel odometry"),
        ("IMU dead reckoning", "IMU dead reckoning"),
        ("EKF wheel+IMU", "EKF, VSLAM-config noise"),
        ("EKF @ measured noise", "EKF, measured noise (diag.)"),
        ("VINS-Fusion", "VINS-Fusion"),
        ("ORB-SLAM3", "ORB-SLAM3 GPU, LC run"),
        ("ORB-SLAM3 (no LC)", "ORB-SLAM3 GPU, no-LC run")]

CAPTION = (
    r"Relative pose error at $\Delta t=\SI{1}{\second}$, RMSE over all pairs "
    r"and over pairs that span no detected jump (a step above "
    r"\SI{10}{\metre\per\second} between consecutive poses); the jump count is "
    r"per run. Computed on the unaligned poses, so this column is independent "
    r"of the rigid fit the ATE of \cref{tab:exp1-accuracy} uses. The two "
    r"filter rows are the two noise models of \cref{tab:exp1-accuracy} in the "
    r"same order. \textbf{Bold} marks the lowest jump-free translational RPE "
    r"of a recording.")


def main():
    rows = {}
    for r in csv.DictReader(open(SRC)):
        if "realistic" in r["dataset"] and r["delta_s"] == DELTA:
            rows[(r["dataset"], r["name"])] = r

    out = ["% Generated by script/make_exp1_rpe_table.py -- do not edit by hand.",
           r"\begin{table}[htbp]", r"\centering",
           r"\caption[Relative pose error at $\Delta t=\SI{1}{\second}$ on the four"
           "\n" r"realistic recordings.]{" + CAPTION + "}",
           r"\label{tab:exp1-rpe}", r"\scriptsize",
           r"\setlength{\tabcolsep}{3pt}",
           r"\begin{tabular}{llrrrrr}", r"\toprule",
           r"Recording & Estimator & Jumps & \multicolumn{2}{c}{Translation [\si{\metre}]} "
           r"& \multicolumn{2}{c}{Rotation [\si{\degree}]} \\",
           r" & & & all pairs & clean & all pairs & clean \\", r"\midrule"]

    for bi, ds in enumerate(BAGS):
        if bi:
            out.append(r"\midrule")
        best = min(float(rows[(ds, s)]["trans_rmse_clean"])
                   for s, _ in ARMS if (ds, s) in rows)
        for ai, (src_name, label) in enumerate(ARMS):
            r = rows.get((ds, src_name))
            if r is None:
                continue
            head = (r"\repo{%s}" % ds.split("/")[-1].replace("dataset_allsensor_", "")) if ai == 0 else ""
            tc = float(r["trans_rmse_clean"])
            cell = (r"\textbf{%.3f}" % tc) if abs(tc - best) < 1e-12 else "%.3f" % tc
            out.append("%s & %s & %s & %.3f & %s & %.3f & %.3f \\\\" % (
                head, label, r["jumps"], float(r["trans_rmse"]), cell,
                float(r["rot_rmse"]), float(r["rot_rmse_clean"])))

    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    text = "\n".join(out)
    if "--check" in sys.argv:
        print(text)
        return
    open(OUT, "w").write(text)
    print("wrote", OUT, "(%d data rows, delta = %s s)" % (len(rows), DELTA))


if __name__ == "__main__":
    main()
